import SwiftProtobuf
import XCTest

@testable import SwiftProtoParser

/// Integration tests for client-provided `.proto` files.
///
/// - **Tier 1a** (9 files): standard options only → exact bytes comparison against `protoc`.
/// - **Tier 1b** (2 files): custom extension options (`buf.validate`, `google.api.http`)
///   → targeted comparison of `uninterpreted_option` arrays against `proto-unlinked-gen`
///   (because standard options like `go_package` are stored as typed fields by SwiftProtoParser
///   but as uninterpreted_option by the Go-tool).
///
/// Reference `.pb` files live in `Tests/TestResources/ClientProtoDescriptors/` and are
/// generated by `Scripts/generate_extension_option_descriptors.sh`.
final class ClientProtoIntegrationTests: XCTestCase {

  // MARK: - Tier 1a: standard options only → exact bytes comparison with protoc

